use std::{sync::Arc, time::Duration};

use agentkeys_core::{
    capability_verify::AuthorityConfig,
    chain_profile::{is_loopback_http_endpoint, ChainProfile},
    object_store::ObjectClient,
};
use anyhow::{ensure, Result};
use zeroize::Zeroizing;

pub struct WorkerConfig {
    pub authority: AuthorityConfig,
    pub storage_url: String,
    pub chain_profile: String,
    pub development_kek: Zeroizing<String>,
    pub browser_origins: String,
}

impl WorkerConfig {
    pub fn local(
        profile: &ChainProfile,
        development: bool,
        broker_public_key: String,
        storage_url: String,
        key_file: &str,
        browser_origins: String,
    ) -> Result<Self> {
        profile.require_local_development(development, None)?;
        ensure!(
            is_loopback_http_endpoint(&storage_url),
            "development storage must be on loopback"
        );
        let authority = AuthorityConfig::from_profile(profile, broker_public_key)?;
        let contents = agentkeys_core::protected_file::read_text(key_file)?;
        let development_kek = Zeroizing::new(contents.trim().to_owned());
        let bytes = Zeroizing::new(hex::decode(&*development_kek)?);
        ensure!(
            bytes.len() == 32 && !bytes.iter().all(|byte| *byte == bytes[0]),
            "development encryption key must contain 32 randomly generated bytes"
        );
        Ok(Self {
            authority,
            storage_url,
            chain_profile: profile.name.clone(),
            development_kek,
            browser_origins,
        })
    }
}

pub struct WorkerState {
    pub config: WorkerConfig,
    pub storage: ObjectClient,
    pub http: reqwest::Client,
    pub audit: crate::audit::AuditEmitter,
}

pub type SharedWorkerState = Arc<WorkerState>;

impl WorkerState {
    pub fn build(config: WorkerConfig, audit: crate::audit::AuditEmitter) -> Result<Self> {
        let storage = ObjectClient::http(&config.storage_url)?;
        Ok(Self {
            config,
            storage,
            http: reqwest::Client::builder()
                .no_proxy()
                .redirect(reqwest::redirect::Policy::none())
                .timeout(Duration::from_secs(30))
                .build()?,
            audit,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use agentkeys_core::chain_profile::{ChainKind, ContractInfo};
    use p256::pkcs8::{EncodePublicKey, LineEnding};
    use rand_core::RngCore;

    #[test]
    fn local_configuration_requires_local_profile_and_private_key_file() {
        let directory = tempfile::tempdir().unwrap();
        let key_file = directory.path().join("encryption.key");
        let key_file = key_file.to_str().unwrap();
        let mut key = [0; 32];
        rand_core::OsRng.fill_bytes(&mut key);
        agentkeys_core::protected_file::write(key_file, hex::encode(key).as_bytes(), true).unwrap();
        let signer = p256::SecretKey::random(&mut rand_core::OsRng);
        let public = signer
            .public_key()
            .to_public_key_pem(LineEnding::LF)
            .unwrap();
        let mut profile = ChainProfile::load_builtin("anvil").unwrap();
        profile.contracts = ["SidecarRegistry", "AgentKeysScope", "K3EpochCounter"]
            .iter()
            .enumerate()
            .map(|(index, name)| ContractInfo {
                name: name.to_string(),
                address: format!("0x{:040x}", index + 1),
                purpose: String::new(),
                deployed_at: String::new(),
            })
            .collect();
        let configured = |profile: &ChainProfile, enabled, endpoint: &str, path: &str| {
            WorkerConfig::local(
                profile,
                enabled,
                public.clone(),
                endpoint.into(),
                path,
                String::new(),
            )
        };
        assert!(configured(&profile, true, "http://127.0.0.1:1", key_file).is_ok());
        assert!(configured(&profile, false, "http://127.0.0.1:1", key_file).is_err());
        assert!(configured(&profile, true, "http://192.0.2.1", key_file).is_err());
        profile.chain_kind = ChainKind::EthereumL1;
        assert!(configured(&profile, true, "http://127.0.0.1:1", key_file).is_err());
        profile.chain_kind = ChainKind::LocalDev;
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(key_file, std::fs::Permissions::from_mode(0o644)).unwrap();
        assert!(configured(&profile, true, "http://127.0.0.1:1", key_file).is_err());
        std::fs::set_permissions(key_file, std::fs::Permissions::from_mode(0o600)).unwrap();
        let link = directory.path().join("linked.key");
        std::os::unix::fs::symlink(key_file, &link).unwrap();
        assert!(configured(&profile, true, "http://127.0.0.1:1", link.to_str().unwrap()).is_err());
        agentkeys_core::protected_file::write(key_file, "00".repeat(32).as_bytes(), false).unwrap();
        assert!(configured(&profile, true, "http://127.0.0.1:1", key_file).is_err());
    }
}
