pub const BASE_URL: &str = "AGENTKEYS_MODEL_BASE_URL";
pub const API_KEY: &str = "AGENTKEYS_MODEL_API_KEY";
pub const MODEL_ID: &str = "AGENTKEYS_MODEL_ID";
pub const SPEECH_URL: &str = "AGENTKEYS_GATE_SPEECH_URL";
pub const ENVIRONMENT_NAMES: [&str; 4] = [BASE_URL, API_KEY, MODEL_ID, SPEECH_URL];

pub fn relay_environment(base_url: &str, api_key: String, model_id: &str) -> Vec<(String, String)> {
    let base_url = base_url.trim_end_matches('/');
    vec![
        (BASE_URL.into(), base_url.into()),
        (API_KEY.into(), api_key),
        (MODEL_ID.into(), model_id.into()),
        (SPEECH_URL.into(), relay_origin(base_url).into()),
    ]
}

pub fn relay_origin(base_url: &str) -> &str {
    let base_url = base_url.trim_end_matches('/');
    base_url.strip_suffix("/v1").unwrap_or(base_url)
}

pub fn validate_environment<'a>(
    read: impl Fn(&str) -> Option<&'a str>,
) -> Result<(), &'static str> {
    if ENVIRONMENT_NAMES.iter().all(|name| read(name).is_none()) {
        return Ok(());
    }
    let base_url =
        read(BASE_URL).ok_or("model endpoint and credential must be supplied together")?;
    let api_key = read(API_KEY).ok_or("model endpoint and credential must be supplied together")?;
    crate::model_config::base_url(base_url)?;
    if api_key.trim().is_empty()
        || api_key
            .bytes()
            .any(|byte| byte.is_ascii_control() || byte.is_ascii_whitespace())
    {
        return Err("model credential is empty or invalid");
    }
    if let Some(model) = read(MODEL_ID) {
        if model.trim().is_empty() || model.bytes().any(|byte| byte.is_ascii_control()) {
            return Err("model identifier is empty or invalid");
        }
    }
    if let Some(speech_url) = read(SPEECH_URL) {
        crate::model_config::base_url(speech_url)?;
        if speech_url != relay_origin(base_url) {
            return Err("speech endpoint must belong to the configured model relay");
        }
    }
    Ok(())
}

pub fn typescript() -> String {
    let mut output = "// Generated by agentkeys-protocol; do not edit.\n".to_owned();
    for (name, value) in [
        ("BASE_URL", BASE_URL),
        ("API_KEY", API_KEY),
        ("MODEL_ID", MODEL_ID),
        ("SPEECH_URL", SPEECH_URL),
    ] {
        output.push_str(&format!("export const {name} = {value:?};\n"));
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    #[test]
    fn runtime_pair_is_explicit_and_errors_never_echo_credentials() {
        let values: BTreeMap<_, _> = relay_environment(
            "http://localhost:8077/v1/",
            "synthetic-key".into(),
            "fixture-model",
        )
        .into_iter()
        .collect();
        assert!(validate_environment(|name| values.get(name).map(String::as_str)).is_ok());
        for name in [BASE_URL, API_KEY] {
            let mut invalid = values.clone();
            invalid.remove(name);
            assert!(validate_environment(|name| invalid.get(name).map(String::as_str)).is_err());
        }
        for (name, value) in [
            (BASE_URL, "http://synthetic-key@localhost/v1"),
            (API_KEY, "synthetic-key\nOTHER=1"),
            (MODEL_ID, ""),
            (SPEECH_URL, "http://other.example"),
        ] {
            let mut invalid = values.clone();
            invalid.insert(name.into(), value.into());
            let error =
                validate_environment(|name| invalid.get(name).map(String::as_str)).unwrap_err();
            assert!(!error.contains("synthetic-key"));
        }
        assert!(validate_environment(|_| None).is_ok());
        assert_eq!(
            relay_origin("http://localhost:8077/v1/"),
            "http://localhost:8077"
        );
        assert_eq!(
            relay_origin("http://localhost:8077"),
            "http://localhost:8077"
        );
    }

    #[test]
    fn javascript_runtime_names_match_the_protocol_owner() {
        assert_eq!(
            typescript(),
            include_str!("../../../packages/agentkeys-dsh/src/generated/model-runtime.ts")
        );
    }
}
